function initialLanguage() {
  const saved = globalThis.localStorage?.getItem(STORAGE_KEY);
  if (saved === 'zh-CN' || saved === 'en') return saved;
  return globalThis.navigator?.language?.toLowerCase().startsWith('zh') ? 'zh-CN' : DEFAULT_LANGUAGE;
}

const WorkstationI18nContext = createContext(null);

export function WorkstationI18nProvider({ children }) {
  const [language, setLanguage] = useState(initialLanguage);

  useEffect(() => {
    globalThis.localStorage?.setItem(STORAGE_KEY, language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo(() => ({
    language,
    setLanguage,
    toggleLanguage: () => setLanguage((current) => current === 'zh-CN' ? 'en' : 'zh-CN'),
    t(key, values = {}) {
      const template = messages[language][key] ?? messages[DEFAULT_LANGUAGE][key] ?? key;
      return Object.entries(values).reduce(
        (result, [name, replacement]) => result.replaceAll(`{${name}}`, String(replacement)),
        template
      );
    }
  }), [language]);

  return <WorkstationI18nContext.Provider value={value}>{children}</WorkstationI18nContext.Provider>;
}

export function useWorkstationI18n() {
  const value = useContext(WorkstationI18nContext);
  if (!value) throw new Error('useWorkstationI18n must be used inside WorkstationI18nProvider');
  return value;
}
