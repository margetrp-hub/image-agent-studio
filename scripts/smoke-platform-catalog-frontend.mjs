import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { chromium } from 'playwright';
import { createServer } from 'vite';

process.env.VITE_STUDIO_STANDALONE = 'true';
const server = await createServer({ logLevel: 'silent', server: { host: '127.0.0.1', port: 0, strictPort: false } });
const user = { id: 'platform-ui-admin', username: 'admin', role: 'admin', active: true, credits: { balance: 1000 } };
const image = { id: 'gpt-image-2', name: 'Published Image', enabled: true, supported: true, available: true, capabilities: { textToImage: true, imageEdit: true, videoGeneration: false }, prices: { image: 9, edit: null, video: null } };
let providers = [{ id: 'platform-one', name: 'Platform One', providerId: 'openai-compatible', baseUrl: 'https://platform.example/v1', enabled: true, hasApiKey: true, models: [image, { ...image, id: 'unsupported', name: 'Unsupported', supported: false, enabled: false }, ...Array.from({ length: 65 }, (_, index) => ({ ...image, id: `unpublished-${index}`, enabled: false }))] }];
const requests = [];
const artifactDir = resolve('output/playwright/platform-catalog');
const errors = [];
let catalogEnabled = true;
let failCatalog = false;
let browser;
try {
  await server.listen();
  const baseUrl = server.resolvedUrls.local[0];
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1360, height: 900 }, reducedMotion: 'reduce' });
  page.on('pageerror', (error) => errors.push(error.message));
  await page.addInitScript((admin) => {
    localStorage.setItem('image-agent-studio:session:v1', JSON.stringify({ accessToken: 'ui-test-token', user: admin, expiresAt: Date.now() + 3600000 }));
    if (!localStorage.getItem('platform-test-initialized')) {
      localStorage.setItem('image-sub2api-studio:provider-settings:v1', JSON.stringify({ apiKeySource: 'manual', providerId: 'openai-compatible', manualGatewayBaseUrl: 'https://byok.example/v1' }));
      sessionStorage.setItem('image-sub2api-studio:manual-provider-secret:v1', 'byok-test-secret');
      localStorage.setItem('platform-test-initialized', '1');
    }
  }, user);
  await page.route('**/studio-api/**', async (route) => {
    const request = route.request();
    const path = new URL(request.url()).pathname.replace('/studio-api', '');
    const input = request.postData() ? JSON.parse(request.postData()) : null;
    requests.push({ path, method: request.method(), input, authorization: request.headers().authorization });
    let body = { ok: true };
    let status = 200;
    if (path === '/auth/admin/providers') {
      if (request.method() === 'POST') {
        const provider = { ...input, id: 'created-provider', enabled: false, hasApiKey: Boolean(input.apiKey), models: [] };
        delete provider.apiKey;
        providers.push(provider);
        body.provider = provider;
      } else body.providers = providers;
    } else if (path.startsWith('/auth/admin/providers/')) {
      const id = path.split('/')[4];
      const provider = providers.find((item) => item.id === id);
      if (request.method() === 'DELETE') providers = providers.filter((item) => item.id !== id);
      else if (path.endsWith('/models')) body.provider = provider;
      else {
        if (input.models) input.models = input.models.map((model) => ({ ...provider.models.find((item) => item.id === model.id), ...model }));
        Object.assign(provider, input);
        delete provider.apiKey;
        body.provider = provider;
      }
    } else if (path === '/auth/platform-models') {
      if (failCatalog) { status = 503; body = { error: 'CATALOG_UNAVAILABLE' }; }
      else body = { ok: true, creditsEnabled: catalogEnabled, providers: catalogEnabled ? providers.filter((provider) => provider.enabled).map(({ id, name, providerId, models }) => ({ id, name, providerId, models: models.filter((model) => model.enabled && model.supported && model.available) })) : [] };
    } else if (path === '/auth/me') body.user = user;
    else if (path === '/auth/config') body = { ok: true, credits: { enabled: true }, providerConnections: { enabled: true }, registration: { enabled: true } };
    else if (path === '/auth/admin/billing/settings') body.settings = { creditsEnabled: true, providerBindingEnabled: true };
    else if (path === '/auth/admin/billing/stats') body.stats = {};
    else if (path === '/auth/admin/users') body.users = [user];
    else if (path === '/auth/admin/update/status') body.update = { state: 'idle', currentVersion: '1.0.30' };
    else if (path === '/auth/admin/system') body.system = {};
    else if (path === '/model-sync') body.models = [{ id: 'gpt-image-2', label: 'BYOK Image' }];
    else if (path === '/library') body = { ok: true, cases: [], categories: [], styles: [], scenes: [] };
    else if (path === '/history') body = { ok: true, records: [], total: 0, nextOffset: null };
    else if (path === '/session') body.session = null;
    else if (path === '/generation-jobs') body = request.method() === 'POST' ? { ok: true, job: { id: 'platform-job', status: 'queued', prompt: input.request.prompt } } : { ok: true, jobs: [] };
    else if (path === '/generation-jobs/platform-job') body.job = { id: 'platform-job', status: 'failed', error: 'Test upstream stopped after request verification' };
    await route.fulfill({ status, contentType: 'application/json', body: JSON.stringify(body) });
  });
  await page.goto(new URL('admin.html#providers', baseUrl).href);
  await page.getByRole('heading', { name: 'Platform One / 模型定价' }).waitFor();
  assert.equal(await page.locator('.iasPlatformModels tbody tr').count(), 50, 'Large catalogs must be paginated.');
  await page.getByLabel('下一页模型').click();
  assert.equal(await page.locator('.iasPlatformModels tbody tr').count(), 17);
  await page.getByLabel('搜索模型').fill('gpt-image-2');
  await page.getByLabel('gpt-image-2 生图积分').fill('0');
  await page.getByText('有未保存的定价修改').waitFor();
  assert.equal(await page.evaluate(() => !window.dispatchEvent(new Event('beforeunload', { cancelable: true }))), true, 'Unsaved pricing must protect refresh.');
  page.once('dialog', (dialog) => dialog.dismiss());
  await page.getByRole('link', { name: '用户账户' }).click();
  assert.match(page.url(), /#providers$/);
  assert.equal(await page.getByLabel('gpt-image-2 生图积分').inputValue(), '0');
  await page.getByRole('button', { name: '保存定价' }).click();
  await page.getByText('模型定价已保存。').waitFor();
  const pricing = requests.findLast((item) => item.input?.models);
  assert.equal(pricing.input.models.find((model) => model.id === image.id).prices.image, 0);
  assert.equal(pricing.input.models.find((model) => model.id === image.id).prices.edit, null);
  assert.equal(pricing.input.models.length, 67, 'Paging must preserve the complete replacement payload.');
  await page.getByRole('button', { name: '编辑 Platform One', exact: true }).click();
  assert.equal(await page.getByLabel('API Key', { exact: true }).inputValue(), '');
  await page.getByLabel('名称', { exact: true }).fill('Platform Renamed');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await page.getByRole('heading', { name: 'Platform Renamed / 模型定价' }).waitFor();
  const rename = requests.findLast((item) => item.input?.name === 'Platform Renamed');
  assert.equal('apiKey' in rename.input, false, 'Blank key must never overwrite server secret.');
  assert.equal('enabled' in rename.input, false, 'Name-only edit must preserve provider availability.');
  await page.getByLabel('搜索模型').fill('unsupported');
  assert.equal(await page.getByRole('switch', { name: '发布 unsupported', exact: true }).isDisabled(), true);
  assert.match(await page.locator('.iasPlatformModels tbody').innerText(), /暂不支持调用/);
  await page.getByRole('button', { name: '新增供应商' }).click();
  await page.getByLabel('名称', { exact: true }).fill('New Draft');
  await page.getByLabel('接口地址', { exact: true }).fill('https://draft.example/v1');
  await page.getByLabel('API Key', { exact: true }).fill('new-test-key');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await page.getByRole('heading', { name: 'New Draft / 模型定价' }).waitFor();
  assert.equal(providers.find((provider) => provider.name === 'New Draft').enabled, false);
  await mkdir(artifactDir, { recursive: true });
  await page.screenshot({ path: resolve(artifactDir, 'admin-desktop.png'), animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByLabel('编辑 New Draft', { exact: true }).click();
  const dialogBounds = await page.getByRole('dialog').boundingBox();
  assert.ok(dialogBounds.x >= 0 && dialogBounds.x + dialogBounds.width <= 390);
  await page.screenshot({ path: resolve(artifactDir, 'admin-mobile.png'), animations: 'disabled' });
  await page.getByLabel('接口地址', { exact: true }).fill('https://new-draft.example/v1');
  page.once('dialog', (dialog) => dialog.dismiss());
  await page.getByRole('dialog').getByLabel('关闭', { exact: true }).click();
  assert.equal(await page.getByLabel('接口地址', { exact: true }).inputValue(), 'https://new-draft.example/v1');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await page.getByText('连接已更新，供应商已停用，待重新同步模型。').waitFor();
  assert.equal(requests.findLast((item) => item.input?.baseUrl === 'https://new-draft.example/v1').input.enabled, false);
  await page.getByLabel('同步 New Draft 模型', { exact: true }).click();
  await page.getByText('模型已同步。').waitFor();
  await page.getByLabel('删除 New Draft', { exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: '删除', exact: true }).click();
  await page.getByText('供应商已删除。').waitFor();
  assert.ok(requests.some((item) => item.path === '/auth/admin/providers/created-provider' && item.method === 'DELETE'));
  await page.setViewportSize({ width: 1360, height: 900 });
  await page.goto(new URL('studio.html', baseUrl).href);
  await page.waitForSelector('.creationDesk');
  assert.equal(await page.locator('.firstRunDialog').count(), 0, 'Existing BYOK users must not be forced through platform onboarding.');
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('image-sub2api-studio:provider-settings:v1')).apiKeySource), 'manual', 'Published platform models must not automatically replace BYOK.');
  await page.locator('.singleField select').first().selectOption('platform:platform-one');
  await page.waitForFunction(() => document.querySelector('.singleFieldGrid')?.textContent?.includes('0 积分/张'));
  assert.equal(await page.locator('.singleField select').nth(1).locator('option').count(), 1);
  await page.locator('.singlePromptBox textarea').fill('A small red square');
  await page.locator('.singleGenerateButton').click();
  await page.locator('.generationConfirmDialog').waitFor();
  assert.match(await page.locator('.generationConfirmDialog').innerText(), /0 积分\/张/);
  const submitted = page.waitForRequest((request) => request.url().endsWith('/studio-api/generation-jobs') && request.method() === 'POST');
  await page.getByRole('button', { name: '确认生成', exact: true }).click();
  await submitted;
  const job = requests.findLast((item) => item.path === '/generation-jobs' && item.method === 'POST');
  assert.equal(job.input.request.apiKeySource, 'platform');
  assert.equal(job.input.request.platformProviderId, 'platform-one');
  assert.equal('apiKey' in job.input, false);
  assert.equal('gatewayBaseUrl' in job.input, false);
  assert.equal('prices' in job.input.request, false);
  await page.screenshot({ path: resolve(artifactDir, 'workstation-desktop.png'), animations: 'disabled' });
  await page.reload();
  await page.waitForFunction(() => document.querySelector('.singleField select')?.value === 'platform:platform-one');
  const byokId = await page.locator('.singleField select').first().locator('option').first().getAttribute('value');
  await page.locator('.singleField select').first().selectOption(byokId);
  const restored = await page.evaluate(() => JSON.parse(localStorage.getItem('image-sub2api-studio:provider-settings:v1')));
  assert.equal(restored.apiKeySource, 'manual');
  assert.equal(restored.manualGatewayBaseUrl, 'https://byok.example/v1');
  const secret = await page.evaluate(() => sessionStorage.getItem('image-sub2api-studio:manual-provider-secret:v1'));
  assert.equal(secret, 'byok-test-secret');
  await page.locator('.singleField select').first().selectOption('platform:platform-one');
  catalogEnabled = false;
  await page.reload();
  await page.waitForFunction(() => document.querySelector('.singleGenerateButton')?.disabled === true);
  assert.equal(await page.locator('.singleField select').nth(1).textContent(), '暂无可用模型');
  failCatalog = true;
  await page.reload();
  await page.waitForFunction(() => document.querySelector('.singleGenerateButton')?.disabled === true);
  assert.equal(await page.locator('.singleField select').nth(1).textContent(), '暂无可用模型');
  catalogEnabled = true;
  failCatalog = false;
  providers[0].models.push({ ...image, id: 'fresh-platform-image', name: 'Fresh Platform Image', prices: { image: 17, edit: null, video: null } });
  const jobsBeforeOnboarding = requests.filter((item) => item.path === '/generation-jobs' && item.method === 'POST').length;
  await page.evaluate(() => {
    localStorage.clear();
    sessionStorage.clear();
    // Prevent the test's BYOK seed; application storage starts empty apart from auth.
    localStorage.setItem('platform-test-initialized', '1');
  });
  await page.reload();
  await page.locator('.firstRunDialog').waitFor();
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('image-sub2api-studio:provider-settings:v1')).apiKeySource), 'manual');
  await page.getByRole('button', { name: '使用平台模型', exact: true }).click();
  await page.getByLabel('平台供应商', { exact: true }).selectOption('platform-one');
  await page.getByLabel('平台模型', { exact: true }).selectOption(JSON.stringify(['fresh-platform-image', 'image']));
  assert.equal(await page.locator('.firstRunDialog input[type=password]').count(), 0, 'Platform onboarding must not require a personal key.');
  assert.match(await page.locator('.firstRunConnectionSummary').innerText(), /17 积分\/张/);
  assert.equal(requests.filter((item) => item.path === '/generation-jobs' && item.method === 'POST').length, jobsBeforeOnboarding);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: resolve(artifactDir, 'first-run-platform-mobile.png'), animations: 'disabled' });
  await page.getByRole('button', { name: '使用此模型', exact: true }).click();
  await page.locator('.firstRunDialog').waitFor({ state: 'hidden' });
  await page.waitForFunction(() => document.querySelectorAll('.singleField select')[1]?.value === 'fresh-platform-image');
  await page.waitForLoadState('networkidle');
  assert.equal(requests.filter((item) => item.path === '/generation-jobs' && item.method === 'POST').length, jobsBeforeOnboarding, 'Selecting a paid platform model must never submit a generation.');
  assert.equal(await page.locator('.singleField select').first().inputValue(), 'platform:platform-one');
  await page.setViewportSize({ width: 1360, height: 900 });
  await page.locator('.singlePromptBox textarea').fill('An explicitly requested paid image');
  await page.locator('.singleGenerateButton').click();
  await page.locator('.generationConfirmDialog').waitFor();
  assert.match(await page.locator('.generationConfirmDialog').innerText(), /17 积分\/张/);
  assert.equal(requests.filter((item) => item.path === '/generation-jobs' && item.method === 'POST').length, jobsBeforeOnboarding, 'The confirmation dialog must not itself submit the request.');
  const firstPaidRequest = page.waitForRequest((request) => request.url().endsWith('/studio-api/generation-jobs') && request.method() === 'POST');
  await page.getByRole('button', { name: '确认生成', exact: true }).click();
  await firstPaidRequest;
  const freshJob = requests.findLast((item) => item.path === '/generation-jobs' && item.method === 'POST');
  assert.equal(freshJob.input.request.model, 'fresh-platform-image');
  assert.equal(freshJob.input.request.apiKeySource, 'platform');
  assert.equal('apiKey' in freshJob.input, false);
  assert.deepEqual(errors, []);
  console.log('Platform frontend smoke passed: admin CRUD/prices/pagination/unsaved guard, responsive dialogs, catalog selection, published price, key-free generation, BYOK preservation, reload/catalog failures, and fresh onboarding with explicit paid generation.');
} finally {
  await browser?.close();
  await server.close();
}
